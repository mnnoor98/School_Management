export class AcademicPerformanceReportComponent implements OnInit, OnDestroy {
  private examStore = inject(ExamStoreService);
  private academicStore = inject(AcademicStoreService);
  private studentStore = inject(StudentStoreService);
  private auth = inject(AuthService);
  private campus = inject(CampusSessionService);
  private toast = inject(ToastService);
  private route = inject(ActivatedRoute);
  private cdr = inject(ChangeDetectorRef);

  private sub = new Subscription();

  schoolName = 'Scholars International Academy';
  schoolAddress = 'Plot 14, Road 2, Block-E, Dhaka 1212, Bangladesh';
  currentUser: User | null = null;

  get activeCampusName(): string {
    const bId = this.campus.branchId;
    if (bId === 'br-02c70f') return 'Dhanmondi Campus';
    if (bId === 'br-8996de') return 'Uttara Campus';
    if (bId === 'br-6fd98e') return 'Rayerbag Campus';
    return 'Main Campus (Central)';
  }

  // Master options
  exams: Exam[] = [];
  classes: SchoolClass[] = [];
  sections: Section[] = [];

  // Selected filters
  selectedExamId = '';
  selectedClassId = '';
  selectedSectionId = 'ALL';
  searchQuery = '';
  isLoading = false;

  // Real Database Merit Matrix Data
  meritRows: MeritTableRow[] = [];
  evaluatedStudentsCount = 0;
  passedCount = 0;
  failedCount = 0;
  passRatePercentage = 0;
  highestGpa = 0.0;
  classAverageScore = 0.0;

  // Modal State for Individual Card
  isCardModalOpen = false;
  selectedStudentForCard: MeritTableRow | null = null;
  isBulkPrinting = false;

  get todayDateFormatted(): string {
    const opts: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'short', year: 'numeric' };
    return new Date().toLocaleDateString('en-US', opts);
  }

  async ngOnInit() {
    this.currentUser = this.auth.getCurrentUser();

    // 1. Load real classes and exams in parallel from backend API
    await Promise.all([
      this.loadExamsList(),
      this.loadClassesList()
    ]);

    // 2. Check query params for exam/class
    this.sub.add(
      this.route.queryParams.subscribe(params => {
        if (params['examId'] && this.exams.some(e => e.id === params['examId'])) {
          this.selectedExamId = params['examId'];
        }
        if (params['classId'] && this.classes.some(c => c.id === params['classId'])) {
          this.selectedClassId = params['classId'];
          this.updateSections();
        }
        if (params['sectionId']) {
          this.selectedSectionId = params['sectionId'];
        }
        if (this.selectedExamId && this.selectedClassId) {
          this.loadMeritReport();
        }
      })
    );

    // 3. React to campus changes
    this.sub.add(
      this.campus.changed$.subscribe(async () => {
        await Promise.all([this.loadExamsList(), this.loadClassesList()]);
        if (this.selectedExamId && this.selectedClassId) {
          this.loadMeritReport();
        }
      })
    );

    if (this.selectedExamId && this.selectedClassId && this.meritRows.length === 0) {
      await this.loadMeritReport();
    }
  }

  ngOnDestroy() {
    this.sub.unsubscribe();
  }

  async loadExamsList() {
    try {
      const data = await this.examStore.loadExams();
      this.exams = data || [];
      if (this.exams.length > 0 && !this.selectedExamId) {
        this.selectedExamId = this.exams[0].id;
      }
    } catch (e: any) {
      console.error('Error loading exams:', e);
    }
  }

  async loadClassesList() {
    try {
      const data = await this.academicStore.loadClasses();
      this.classes = data || [];
      if (this.classes.length > 0 && !this.selectedClassId) {
        // Auto-select Class Two or Class 10 or first class
        const preferred = this.classes.find(c => c.name.toLowerCase() === 'two' || c.code.toLowerCase() === 'cls-04')
          || this.classes.find(c => c.name.toLowerCase().includes('10'))
          || this.classes[0];
        this.selectedClassId = preferred ? preferred.id : this.classes[0].id;
        this.updateSections();
      }
    } catch (e: any) {
      console.error('Error loading classes:', e);
    }
  }

  updateSections() {
    const allSections = this.academicStore.getSections();
    this.sections = allSections.filter(s => !this.selectedClassId || s.classId === this.selectedClassId);
    this.selectedSectionId = 'ALL';
  }

  onClassChange() {
    this.updateSections();
    this.loadMeritReport();
  }

  onFilterChange() {
    this.loadMeritReport();
  }

  getSelectedExamName(): string {
    const e = this.exams.find(x => x.id === this.selectedExamId);
    return e ? `${e.name} (${e.term})` : 'Term Examination';
  }

  getSelectedClassName(): string {
    const c = this.classes.find(x => x.id === this.selectedClassId);
    return c ? c.name : 'Selected Class';
  }

  getSelectedSectionName(): string {
    if (this.selectedSectionId === 'ALL') return 'All Sections';
    const s = this.sections.find(x => x.id === this.selectedSectionId);
    return s ? `Section ${s.name}` : 'All Sections';
  }

  // --- CORE: FETCH & COMPILE REAL DATABASE MARKS & MERIT STANDINGS ---
  async loadMeritReport() {
    if (!this.selectedExamId || !this.selectedClassId) {
      return;
    }

    this.isLoading = true;
    this.cdr.markForCheck();

    try {
      // 1. Fetch real class marksheets directly from PostgreSQL Backend API
      const marksheets = await this.examStore.fetchClassMarksheet(
        this.selectedExamId,
        this.selectedClassId,
        this.selectedSectionId === 'ALL' ? undefined : this.selectedSectionId
      );

      // 2. Map database results to table rows
      if (marksheets && marksheets.length > 0) {
        const rows: MeritTableRow[] = marksheets.map(sheet => {
          const totalObtained = sheet.totalObtained || 0;
          const fullMarks = sheet.totalMarks || (sheet.marks && sheet.marks.length > 0 ? sheet.marks.length * 100 : 0);
          const pct = fullMarks > 0 ? Number(((totalObtained / fullMarks) * 100).toFixed(1)) : 0;
          const isPass = sheet.letterGrade !== 'F' && sheet.letterGrade !== 'N/A' && sheet.gpa > 0;

          const marksList: StudentSubjectScore[] = (sheet.marks || []).map(m => {
            const ob = m.obtainedMarks || 0;
            const fm = m.fullMarks || 100;
            const gp = (m as any).gpa !== undefined ? (m as any).gpa : (m.gradePoint !== undefined ? m.gradePoint : (ob >= 80 ? 5.0 : ob >= 70 ? 4.0 : ob >= 60 ? 3.5 : ob >= 50 ? 3.0 : ob >= 33 ? 1.0 : 0.0));
            return {
              subjectName: m.subjectName || 'Subject',
              fullMarks: fm,
              obtainedMarks: ob,
              grade: m.grade || (ob >= 80 ? 'A+' : ob >= 70 ? 'A' : ob >= 60 ? 'A-' : ob >= 50 ? 'B' : ob >= 33 ? 'D' : 'F'),
              gpa: gp
            };
          });

          return {
            position: sheet.positionInClass || 1,
            positionLabel: this.formatPositionLabel(sheet.positionInClass || 1),
            studentId: sheet.student?.id || '',
            studentName: sheet.student?.fullName || 'Student',
            admissionNo: sheet.student?.admissionNo || 'ADM-2026',
            rollNo: sheet.student?.rollNo || '01',
            className: sheet.student?.className || this.getSelectedClassName(),
            sectionName: sheet.student?.sectionName || 'General',
            guardianName: sheet.student?.guardianName,
            guardianPhone: sheet.student?.guardianPhone,
            totalObtained,
            fullMarks,
            percentage: pct,
            gpa: Number((sheet.gpa || 0).toFixed(2)),
            letterGrade: sheet.letterGrade || (isPass ? (sheet.gpa >= 5.0 ? 'A+' : sheet.gpa >= 4.0 ? 'A' : 'B') : 'F'),
            isPass,
            remarks: sheet.remarks || (isPass ? (sheet.gpa >= 5.0 ? 'Exceptional academic performance' : 'Good academic standing') : 'Remedial assessment required'),
            subjectCount: marksList.length,
            marks: marksList
          };
        });

        // Sort by Merit: Passing first (by position, then GPA desc, then score desc), then failing
        rows.sort((a, b) => {
          if (a.isPass && !b.isPass) return -1;
          if (!a.isPass && b.isPass) return 1;
          if (a.position !== b.position) return a.position - b.position;
          if (b.gpa !== a.gpa) return b.gpa - a.gpa;
          return b.totalObtained - a.totalObtained;
        });

        // Re-assign accurate position labels
        this.meritRows = rows.map((r, idx) => ({
          ...r,
          position: idx + 1,
          positionLabel: this.formatPositionLabel(idx + 1)
        }));

        // Compute KPIs from REAL data
        this.evaluatedStudentsCount = this.meritRows.length;
        this.passedCount = this.meritRows.filter(r => r.isPass).length;
        this.failedCount = this.meritRows.filter(r => !r.isPass).length;
        this.passRatePercentage = this.evaluatedStudentsCount > 0
          ? Number(((this.passedCount / this.evaluatedStudentsCount) * 100).toFixed(1))
          : 0;
        this.highestGpa = this.meritRows.length > 0 ? Math.max(...this.meritRows.map(r => r.gpa)) : 0.0;
        const totalPctSum = this.meritRows.reduce((acc, r) => acc + r.percentage, 0);
        this.classAverageScore = this.evaluatedStudentsCount > 0
          ? Number((totalPctSum / this.evaluatedStudentsCount).toFixed(1))
          : 0.0;
      } else {
        // Zero marksheets found in DB
        this.meritRows = [];
        this.evaluatedStudentsCount = 0;
        this.passedCount = 0;
        this.failedCount = 0;
        this.passRatePercentage = 0;
        this.highestGpa = 0.0;
        this.classAverageScore = 0.0;
      }
    } catch (err: any) {
      console.error('Failed to load academic merit report:', err);
      this.toast.error('Ledger Error', 'Could not load academic marksheet from database.');
      this.meritRows = [];
    } finally {
      this.isLoading = false;
      this.cdr.markForCheck();
    }
  }

  get filteredMeritRows(): MeritTableRow[] {
    const q = this.searchQuery.trim().toLowerCase();
    if (!q) return this.meritRows;
    return this.meritRows.filter(r =>
      r.studentName.toLowerCase().includes(q) ||
      r.rollNo.includes(q) ||
      r.admissionNo.toLowerCase().includes(q) ||
      r.sectionName.toLowerCase().includes(q)
    );
  }

  formatPositionLabel(pos: number): string {
    if (pos === 1) return '1st Place 🥇';
    if (pos === 2) return '2nd Place 🥈';
    if (pos === 3) return '3rd Place 🥉';
    return `#${pos < 10 ? '0' + pos : pos}`;
  }

  getPositionClass(pos: number, isPass: boolean): string {
    if (!isPass) return 'pos-regular';
    if (pos === 1) return 'pos-gold';
    if (pos === 2) return 'pos-silver';
    if (pos === 3) return 'pos-bronze';
    return 'pos-regular';
  }

  getGradeBadgeClass(grade: string): string {
    const g = (grade || '').toUpperCase();
    if (g === 'A+') return 'grade-a-plus';
    if (g === 'A') return 'grade-a';
    if (g === 'A-') return 'grade-a-minus';
    if (g === 'B') return 'grade-b';
    if (g === 'C') return 'grade-c';
    if (g === 'D') return 'grade-d';
    return 'grade-f';
  }

  // --- INDIVIDUAL PROGRESS REPORT CARD MODAL ---
  viewStudentCard(row: MeritTableRow) {
    this.selectedStudentForCard = row;
    this.isCardModalOpen = true;
  }

  closeCardModal() {
    this.isCardModalOpen = false;
    this.selectedStudentForCard = null;
  }

  printStudentCard() {
    document.body.classList.add('printing-receipt');
    window.print();
    setTimeout(() => {
      document.body.classList.remove('printing-receipt');
    }, 1000);
  }

  printReport() {
    window.print();
  }

  printBulkCards() {
    if (this.meritRows.length === 0) {
      this.toast.warning('No Records', 'Please load examination marksheet before printing result cards.');
      return;
    }
    this.isBulkPrinting = true;
    document.body.classList.add('printing-bulk-cards');
    this.cdr.detectChanges();
    setTimeout(() => {
      window.print();
      setTimeout(() => {
        document.body.classList.remove('printing-bulk-cards');
        this.isBulkPrinting = false;
        this.cdr.detectChanges();
      }, 1000);
    }, 200);
  }

  exportCSV() {
    if (this.meritRows.length === 0) {
      this.toast.warning('Export Empty', 'No merit records to export.');
      return;
    }

    const filename = `Academic_Merit_Matrix_${this.getSelectedClassName().replace(/\\s+/g, '_')}_${this.getSelectedExamName().replace(/\\s+/g, '_')}.csv`;
    let csv = 'Position,Student Name,Admission No,Class Roll,Class,Section,Obtained Marks,Full Marks,Percentage,GPA,Grade,Status,Remarks\\n';

    this.filteredMeritRows.forEach(r => {
      csv += `"${r.positionLabel}","${r.studentName}","${r.admissionNo}","${r.rollNo}","${r.className}","${r.sectionName}","${r.totalObtained}","${r.fullMarks}","${r.percentage}%","${r.gpa.toFixed(2)}","${r.letterGrade}","${r.isPass ? 'PASSED' : 'REMEDIAL'}","${r.remarks}"\\n`;
    });

    const blob = new Blob([csv], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.setAttribute('href', url);
    link.setAttribute('download', filename);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    this.toast.success('Tabulation Exported', `${filename} generated and downloaded.`);
  }
}
